`timescale 1ns/1ps

module magma (
    input  logic         decrypt,     // 0 = шифрование, 1 = дешифрование
    input  logic [63:0]  block_in,    // Входной блок 64 бита
    input  logic [255:0] key,         // Ключ 256 бит
    output logic [63:0]  block_out    // Выходной блок 64 бита
);

    // =====================================================
    // S-BOX (Таблицы подстановок согласно ГОСТ Р 34.12-2015)
    // =====================================================
    localparam logic [3:0] PI [0:7][0:15] = '{
        '{12,4,6,2,10,5,11,9,14,8,13,7,0,3,15,1},
        '{6,8,2,3,9,10,5,12,1,14,4,7,11,13,0,15},
        '{11,3,5,8,2,15,10,13,14,1,7,4,12,9,6,0},
        '{12,8,2,1,13,4,15,6,7,0,10,5,3,14,9,11},
        '{7,15,5,10,8,1,6,13,0,9,3,14,11,4,2,12},
        '{5,13,15,6,9,2,12,10,11,7,8,1,4,3,14,0},
        '{8,14,2,5,6,9,1,12,15,4,11,0,13,10,3,7},
        '{1,7,14,13,0,5,8,3,4,15,10,6,9,12,11,2}
    };

    // =====================================================
    // g-функция (Основа алгоритма Магма)
    // =====================================================
    function automatic logic [31:0] g_func(
        input logic [31:0] x,
        input logic [31:0] k
    );
        logic [31:0] sum;
        logic [31:0] sbox_out;
        
        // 1. Сложение по модулю 2^32
        sum = x + k;
        
        // 2. T-map (подстановка через S-блоки)
        // Обрабатываем 8 нибблов по 4 бита
        for (int i = 0; i < 8; i++) begin
            sbox_out[i*4 +: 4] = PI[i][sum[i*4 +: 4]];
        end

        // 3. Циклический сдвиг влево на 11 бит (ROTL 11)
        g_func = {sbox_out[20:0], sbox_out[31:21]}; 
    endfunction

    // =====================================================
    // Key Schedule (Расширение ключа до 32 раундовых ключей)
    // =====================================================
    logic [31:0] K [0:31];

    always_comb begin
        // Ключ 256 бит делится на 8 подключей по 32 бита
        for (int i = 0; i < 8; i++)
            K[i] = key[255 - i*32 -: 32];

        // Раунды 8-15 и 16-23: повторение K[0...7]
        for (int i = 8; i < 24; i++)
            K[i] = K[i-8];

        // Раунды 24-31: подключи в обратном порядке K[7...0]
        for (int i = 24; i < 32; i++)
            K[i] = K[31-i];
    end

    // =====================================================
    // Feistel Network (Основной цикл)
    // =====================================================
    always_comb begin
        // ВАЖНО: Объявление и присвоение внутри блока для корректного обновления в симуляции
        logic [31:0] L;
        logic [31:0] R;
        logic [31:0] temp;

        L = block_in[63:32];
        R = block_in[31:0];

        if (!decrypt) begin 
            // ==================== ШИФРОВАНИЕ ====================
            for (int i = 0; i < 31; i++) begin
                temp = g_func(R, K[i]) ^ L;
                L = R;
                R = temp;
            end
            // Последний раунд (без финального переброса L и R)
            temp = g_func(R, K[31]) ^ L;
            block_out = {temp, R};
        end 
        else begin 
            // ==================== ДЕШИФРОВАНИЕ ====================
            // В дешифровании ключи используются в обратном порядке
            for (int i = 31; i > 0; i--) begin
                temp = g_func(R, K[i]) ^ L;
                L = R;
                R = temp;
            end
            // Последний раунд (используем первый ключ K[0])
            temp = g_func(R, K[0]) ^ L;
            block_out = {temp, R};
        end
    end

endmodule